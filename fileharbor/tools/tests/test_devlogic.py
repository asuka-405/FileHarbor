import sys; import os; sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from fhtools import devlogic as d
def check(name, got, want):
    ok = want in got if isinstance(want, str) else want(got)
    print(("PASS " if ok else "FAIL ") + name + ("" if ok else "  got=%r" % (got,)))
check("json_format", d.json_format('{"b":1,"a":[1,2]}', 2, True), '"a": [\n    1,')
check("json_error", (lambda: [d.json_format('{"a":')] and "" )() if False else "x", "x")
try: d.json_format('{"a":'); check("json_error", "no error", "ToolError")
except d.ToolError as e: check("json_error", str(e), "Invalid JSON")
check("json_minify", d.json_minify('{ "a" : [1, 2] }'), '{"a":[1,2]}')
check("yaml_roundtrip", d.yaml_to_json(d.json_to_yaml('{"a":{"b":[1,2]}}'), 0), '"b": [')
check("base64", d.base64_decode(d.base64_encode("héllo wörld ✓")), "héllo wörld ✓")
check("base64_nopad", d.base64_decode("aGk"), "hi")
check("url", d.url_decode(d.url_encode("a b&c=é")), "a b&c=é")
check("html", d.html_decode(d.html_encode('<a href="x">&</a>')), '<a href="x">&</a>')
check("hex", d.hex_decode(d.hex_encode("hi!")), "hi!")
check("md5", d.hashes("hello"), "5d41402abc4b2a76b9719d911017c592")
check("sha256", d.hashes("hello"), "2cf24dba5fb0a30e26e83b2ac5b9e29e1b161e5c1fa7425e73043362938b9824")
check("uuid", d.uuids(3), lambda s: len(s.splitlines()) == 3 and all(len(x) == 36 for x in s.splitlines()))
check("ulid", d.ulids(2), lambda s: all(len(x) == 26 for x in s.splitlines()))
check("password", d.password(24, count=3), lambda s: all(len(x) == 24 for x in s.splitlines()))
check("lorem", d.lorem(2, 2), lambda s: s.count("\n\n") == 1)
check("timestamp_num", d.timestamp("0"), "1970-01-01 00:00:00")
check("timestamp_ms", d.timestamp("1700000000000"), "2023-11-14 22:13:20")
check("timestamp_iso", d.timestamp("2023-11-14T22:13:20Z"), "Unix seconds:      1700000000")
check("base", d.number_base("0xFF"), "Decimal: 255")
check("color_hex", d.color_convert("#ff9933"), "RGB: rgb(255, 153, 51)")
check("color_rgb", d.color_convert("rgb(255,153,51)"), "HEX: #ff9933")
check("color_hsl", d.color_convert("hsl(30,100%,60%)"), "HEX: #ff9933")
check("case_snake", d.case_convert("helloWorld fooBar", "snake_case"), "hello_world_foo_bar")
check("case_camel", d.case_convert("hello_world-foo", "camelCase"), "helloWorldFoo")
check("case_pascal", d.case_convert("hello world", "PascalCase"), "HelloWorld")
check("stats", d.text_stats("one two\nthree"), "Words: 3")
check("sort", d.sort_lines("b\na\nb", "a-z", True), "a\nb")
check("diff", d.text_diff("a\nb", "a\nc"), "-b")
tok = "eyJhbGciOiJIUzI1NiJ9.eyJzdWIiOiIxMjMiLCJleHAiOjE1MDAwMDAwMDB9.sig"
check("jwt", d.jwt_decode(tok), "EXPIRED")
check("regex", d.regex_test(r"(\d+)-(?P<w>\w+)", "12-ab 34-cd"), "2 matches")
check("regex_bad", (lambda: d.regex_test("(", "x"))() if False else "x", "x")
try: d.regex_test("(", "x"); check("regex_bad", "no error", "ToolError")
except d.ToolError as e: check("regex_bad", str(e), "Invalid pattern")
check("cron", d.cron_explain("*/5 0 * * 1-5"), "every 5 minute")
check("escape", d.escape_string('a"b\n', "json"), 'a\\"b\\n')
check("unescape", d.escape_string('a\\"b', "unjson"), 'a"b')
